def replace_between(text: str, start_marker: str, end_marker: str, replacement: str) -> str:
    start = text.find(start_marker)
    if start < 0:
        raise RuntimeError(f"start marker not found: {start_marker}")
    end = text.find(end_marker, start)
    if end < 0:
        raise RuntimeError(f"end marker not found after {start_marker}: {end_marker}")
    return text[:start] + replacement.rstrip() + "\n\n" + text[end:]


def replace_formula_image(text: str, filename: str, replacement: str) -> str:
    pattern = re.compile(rf"!\[公式\]\([^)]*{re.escape(filename)}\)")
    text, count = pattern.subn(lambda _match: replacement, text, count=1)
    if count != 1:
        raise RuntimeError(f"formula image not found: {filename}")
    return text


def normalize_spacing(text: str) -> str:
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip() + "\n"


