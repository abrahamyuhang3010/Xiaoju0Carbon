    configure_structured_converter()
    pdfs = target_pdfs()
    paths: list[Path] = []
    for pdf in pdfs:
        paths.extend(output_paths_for(pdf))
    backup_dir = backup(paths)
    print(f"backup_dir={backup_dir}")

    processed: list[tuple[str, dict, int]] = []
    for pdf in pdfs:
        structured = rebuild_from_current_markdown(pdf)
        md_text = pdf.with_suffix(".md").read_text(encoding="utf-8")
        remaining_images = len(FORMULA_IMAGE_RE.findall(md_text))
        quality = structured.get("quality_report", {})
        processed.append((pdf.stem, quality, remaining_images))
        print(
            "{stem}: formulas={formulas} resolved={resolved} unresolved={unresolved} remaining_images={remaining}".format(
                stem=pdf.stem,
                formulas=quality.get("formula_count"),
                resolved=quality.get("resolved_formula_count"),
                unresolved=quality.get("unresolved_formula_count"),
                remaining=remaining_images,
            )
        )

    rebuild_index()
    total_images = sum(remaining for _stem, _quality, remaining in processed)
